"""Separate the frozen MARL portfolio from added public-rubric search tables."""
import argparse
import json
from pathlib import Path

import numpy as np

import routing_announced_selection as experiment

limit, route, base, digest = experiment.limit, experiment.route, experiment.base, experiment.digest


def evaluate(path):
    saved = experiment.read(path)
    assert saved["input_hashes"] == experiment.hashes()
    priors, frozen, trained = experiment.selection_inputs()
    assert list(priors) == saved["priors"]
    seeds = {**frozen, **trained}
    public = np.array(saved["announced_points"])
    reference = np.array([row["independent"] for row in saved["optimized_independence_announced"].values()])
    warm_matrix = route.receipt_matrix(public, route.TRAIN_LOSS)
    original = {}
    baseline = {}
    for name, p in seeds.items():
        for swap in (False, True):
            label = f"{'swapped' if swap else 'forward'}:{name}"
            original[label] = (base.space.as_policy(p), swap)
            if name.startswith("independent_") or name == "skip_all":
                baseline[label] = original[label]
    team = saved["planned_team"]
    search = {name: (base.space.as_policy(candidate["policy"]), candidate["swap_desks"])
              for name, candidate in team["added_policies"].items()}
    mixtures = {}
    for name, candidates in (("without_added_tables", original), ("added_tables_and_silent", {**baseline, **search})):
        scores = []
        for policy, swap in candidates.values():
            cells = limit.pilot.cell_returns(policy, warm_matrix)
            scores.append([np.sum(cells * (p.T if swap else p)) for p in priors.values()])
        gains = np.asarray(scores).T - reference[:, None]
        _, weights = limit.game_search(gains)
        mixtures[name] = (candidates, weights, gains @ weights)
    _, checksum, _, observed = next(row for row in base.held_out() if row[0] == experiment.CASE)
    oracle = experiment.read(limit.PRIOR_BANK)["historical"][experiment.CASE]
    assert checksum == oracle["source_sha256"]
    audit = {}
    for name, (candidates, weights, declared) in mixtures.items():
        gains = {}
        for label, p in priors.items():
            net = sum(weight * route.evaluate(policy, p.T if swap else p, observed, route.TRAIN_LOSS)["net"]
                      for (policy, swap), weight in zip(candidates.values(), weights, strict=True))
            gains[label] = net - oracle["results"][label]["independent"]
        audit[name] = {"declared_worst": float(declared.min()), "observed_worst": min(gains.values()),
                       "observed_gain_by_prior": gains}
    return {
        "scope": "Score locked candidate-menu ablations. All mixture weights use only the announced rubric. "
                 "The added-table menu reuses columns generated by the full planner with a learned warm start.",
        "plan_sha256": digest(path),
        "full_plan_pricing_mass": sum(weight for name, weight in team["feasible_mixture"]["mixture"].items()
                                      if name in search),
        "results": audit,
    }


if __name__ == "__main__":
    cli = argparse.ArgumentParser(description=__doc__)
    cli.add_argument("plan", type=Path)
    print(json.dumps(evaluate(cli.parse_args().plan), indent=2))
